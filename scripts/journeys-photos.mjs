/**
 * Scans public/journeys/<slug>/ for photos and writes lib/journeys/photos.generated.ts.
 *
 *   npm run journeys:photos
 *
 * Add a photo: drop the .jpg/.png/.webp into its destination folder, then describe it in that folder's
 * `_credits.json`:
 *
 *   {
 *     "lamu-old-town-door.jpg": {
 *       "alt": "A carved wooden door in a narrow whitewashed street",   // what is actually in the picture
 *       "credit": "Photographer name / Pexels",
 *       "licence": "pexels",                                           // "pexels" | "unsplash" | "unconfirmed"
 *       "attraction": "Lamu Old Town"                                  // optional: exact attraction name
 *     }
 *   }
 *
 * The first photo (alphabetically, or the one with "hero": true) becomes the destination's hero image.
 * A photo with no entry is still shown, but marked "Photo credit to be confirmed" with a plain placeholder alt.
 * Folders without a _credits.json (Nakuru, which is written by hand in destinations.ts) are skipped.
 */
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";

/** Minimal image size reader (JPEG, PNG, WebP) so the script needs no extra dependency. */
function imageSize(buf) {
  if (buf.length > 24 && buf.readUInt32BE(0) === 0x89504e47) return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length - 9) {
      if (buf[i] !== 0xff) { i++; continue; }
      const m = buf[i + 1];
      if (m === 0xd8 || (m >= 0xd0 && m <= 0xd7) || m === 0x01 || m === 0xff) { i += m === 0xff ? 1 : 2; continue; }
      const len = buf.readUInt16BE(i + 2);
      if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
      i += 2 + len;
    }
  }
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") {
    const t = buf.toString("ascii", 12, 16);
    if (t === "VP8X") return { width: 1 + buf.readUIntLE(24, 3), height: 1 + buf.readUIntLE(27, 3) };
    if (t === "VP8 ") return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
    if (t === "VP8L") { const b = buf.readUInt32LE(21); return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 }; }
  }
  throw new Error("Unsupported or unreadable image");
}

const root = path.resolve("public/journeys");
const out = path.resolve("lib/journeys/photos.generated.ts");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const title = (s) => s.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());

const result = {};
const warnings = [];
for (const slug of (await readdir(root)).sort()) {
  const dir = path.join(root, slug);
  if (!(await stat(dir)).isDirectory()) continue;
  let credits;
  try { credits = JSON.parse(await readFile(path.join(dir, "_credits.json"), "utf8")); } catch { continue; }
  const files = (await readdir(dir)).filter((f) => exts.has(path.extname(f).toLowerCase())).sort();
  const photos = [];
  for (const f of files) {
    const meta = imageSize(await readFile(path.join(dir, f)));
    const c = credits[f];
    if (!c) warnings.push(`${slug}/${f}: no entry in _credits.json (shown with placeholder alt and "credit to be confirmed")`);
    else if (!c.alt) warnings.push(`${slug}/${f}: entry has no "alt" text`);
    photos.push({
      src: `/journeys/${slug}/${f}`,
      alt: c?.alt || `${title(slug)}: ${title(path.basename(f, path.extname(f)))}`,
      width: meta.width, height: meta.height,
      credit: c?.credit || "Photo credit to be confirmed",
      licence: ["pexels", "unsplash"].includes(c?.licence) ? c.licence : "unconfirmed",
      ...(c?.attraction ? { attraction: c.attraction } : {}),
      hero: Boolean(c?.hero),
    });
  }
  photos.sort((a, b) => Number(b.hero) - Number(a.hero));
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  result[slug] = photos.map(({ hero: _hero, ...p }) => p);
}

const body = `// GENERATED by scripts/journeys-photos.mjs — run \`npm run journeys:photos\`. Do not edit by hand.
import type { Photo } from "./types";

export const generatedPhotos: Record<string, Photo[]> = ${JSON.stringify(result, null, 2)};
`;
await writeFile(out, body);
const n = Object.values(result).reduce((a, b) => a + b.length, 0);
console.log(`Wrote ${n} photo(s) across ${Object.keys(result).length} destination folder(s) to lib/journeys/photos.generated.ts`);
for (const w of warnings) console.warn("  ! " + w);
